# banco.exportar_json()
# Procedimento para exportar os dados do Oracle para um arquivo JSON de backup
# param conn: Objeto de conexão ativo com o Oracle
# return: Não retorna nada
def exportar_json(conn):
    desenho.limpar()
    desenho.titulo("EXPORTAR PARA JSON", "Backup de dados em formato JSON")
    print()
    
    plantas = buscar_todas_plantas(conn)
    if not plantas:
        print("    A tabela está vazia, não há o que exportar.")
    else:
        df = pd.DataFrame.from_records(
            plantas, columns=["Id", "Nome", "Tipo", "Quantidade"]
        )
        df.to_json("plantas_cadastradas.json", orient="records", force_ascii=False, indent=4)
        print("    Dados exportados com sucesso para o ficheiro plantas_cadastradas.json.")
        
    desenho.espera_entrada()

# banco.consultar_recurso_api()
# Procedimento para consultar de forma genérica os recursos da API em Java hospedada no Render
# param recurso: String com o endpoint da API a ser consultado
# param titulo_menu: String com o título a ser exibido no terminal
# return: Não retorna nada
def consultar_recurso_api(recurso: str, titulo_menu: str) -> None:
    desenho.limpar()
    desenho.titulo(titulo_menu, "Dados da API Externa")
    print()
    
    url_completa = f"{url_base_api}/{recurso}"
    
    try:
        resposta = requests.get(url_completa, timeout=5)
        if resposta.status_code == 200:
            dados = resposta.json()
            if not dados:
                print(f"    A API não retornou registos para {titulo_menu}.")
            else:
                for item in dados:
                    desenho.linha()
                    for chave, valor in item.items():
                        print(f"    {str(chave).upper():<20}: {valor}")
                    desenho.linha()
                    print()
        else:
            print(f"    Erro ao comunicar com a API: {resposta.status_code}")
    except Exception as e:
        print(f"    Falha na ligação com a API online: {e}")
        
    desenho.espera_entrada()